/* Shared header / footer, breadcrumbs and scroll reveal.
   Brand settings come from config.js (generated by tools/build_pages.py). */
(function () {
  var SITE = window.SITE || { name: "Brand", domain: "example.com", email: "support@example.com" };
  document.documentElement.classList.add("js");

  /* current user (null when signed out); other scripts wait on this promise */
  window.SITE_ME = fetch("/api/auth/me", { credentials: "same-origin", cache: "no-store" })
    .then(function (r) { return r.ok ? r.json().then(function (j) { return j.user; }) : null; })
    .catch(function () { return null; });

  var path = location.pathname.replace(/\/+$/, "") || "/";
  var links = [
    ["/features", "Features"], ["/how-it-works", "How it works"], ["/solutions", "Solutions"],
    ["/faq", "FAQ"], ["/about", "About"],
  ];
  var logo = '<svg viewBox="0 0 64 64" aria-hidden="true" focusable="false"><rect width="64" height="64" rx="15" style="fill:var(--primary)"/>' +
    '<path d="M19 12h19l9 9v31a3 3 0 0 1-3 3H19a3 3 0 0 1-3-3V15a3 3 0 0 1 3-3z" fill="#fff"/><path d="M38 12l9 9H41a3 3 0 0 1-3-3z" fill="#c8d0dc"/>' +
    '<path d="M26 31v14l12-7z" style="fill:var(--accent)"/><rect x="22" y="23" width="14" height="3" rx="1.5" style="fill:var(--primary)"/></svg>';

  /* ---------- design (theme) switcher ---------- */
  var THEMES = [
    { id: "t1", label: "Classic",   sub: "Navy and gold, serif headings",        bg: "#f5f7fa", bar: "#0f1c33", hero: "#1f3a5f", h1: "#fff",    h2: "#c9d6e8", btn: "#b8862b", card: "#fff",    line: "#d5dce6", r: 3, br: 2, meta: "#1f3a5f" },
    { id: "t2", label: "Midnight",  sub: "Dark, glass cards, electric blue",     bg: "#0a1020", bar: "#070c18", hero: "#162447", h1: "#f1f5fb", h2: "#8fa0b8", btn: "#38bdf8", card: "#111a2e", line: "#22304a", r: 5, br: 3, meta: "#0a1020" },
    { id: "t3", label: "Corporate", sub: "Clean, light, sharp corners",          bg: "#ffffff", bar: "#0f62fe", hero: "#f4f4f4", h1: "#161616", h2: "#6f6f6f", btn: "#0f62fe", card: "#fff",    line: "#e0e0e0", r: 0, br: 0, meta: "#0f62fe" },
    { id: "t4", label: "Editorial", sub: "Ivory, forest green, serif display",   bg: "#f6f1e7", bar: "#153a2b", hero: "#efe6d0", h1: "#1f4d3a", h2: "#5d6a62", btn: "#c2562f", card: "#fffdf8", line: "#ddd3bd", r: 7, br: 4, meta: "#1f4d3a" },
    { id: "t5", label: "Vibrant",   sub: "Bold gradients, floating header",      bg: "#f7f5ff", bar: "#2e1065", hero: "#6d28d9", h1: "#fff",    h2: "#ede9fe", btn: "#ec4899", card: "#fff",    line: "#e6e0f7", r: 8, br: 3, meta: "#6d28d9" }
  ];
  var FONTS = {
    t2: "family=Plus+Jakarta+Sans:wght@400;500;600;700;800",
    t4: "family=Playfair+Display:wght@600;700&family=Source+Sans+3:wght@400;500;600;700",
    t5: "family=Sora:wght@500;600;700&family=DM+Sans:wght@400;500;600;700"
  };
  var STORE = "site_theme";

  function currentTheme() {
    var a = document.documentElement.getAttribute("data-theme");
    return /^t[1-5]$/.test(a) ? a : "t1";
  }

  function thumb(x) {
    return '<svg class="tp" viewBox="0 0 72 50" aria-hidden="true" focusable="false">' +
      '<rect width="72" height="50" rx="6" fill="' + x.bg + '"/><rect width="72" height="9" fill="' + x.bar + '"/>' +
      '<rect x="6" y="15" width="38" height="22" rx="' + x.r + '" fill="' + x.hero + '"/>' +
      '<rect x="9" y="19" width="22" height="3" rx="1.5" fill="' + x.h1 + '"/><rect x="9" y="25" width="16" height="2" rx="1" fill="' + x.h2 + '"/>' +
      '<rect x="9" y="31" width="13" height="4" rx="' + x.br + '" fill="' + x.btn + '"/>' +
      '<rect x="48" y="15" width="18" height="22" rx="' + x.r + '" fill="' + x.card + '" stroke="' + x.line + '"/>' +
      '<rect x="6" y="42" width="60" height="3" rx="1.5" fill="' + x.line + '"/></svg>';
  }

  function designMenu() {
    var cur = currentTheme();
    var opts = THEMES.map(function (x, i) {
      var on = x.id === cur;
      return '<button type="button" class="design-opt" role="radio" aria-checked="' + on + '" data-theme-id="' + x.id + '">' +
        thumb(x) + "<span><b>Theme " + (i + 1) + " &middot; " + x.label + "</b><small>" + x.sub + "</small></span>" +
        '<span class="tick"><svg viewBox="0 0 24 24" aria-hidden="true"><path d="M5 12.5l4.5 4.5L19 7.5"/></svg></span></button>';
    }).join("");
    return '<div class="nav-item"><button type="button" class="design-btn" id="designBtn" aria-haspopup="true" aria-expanded="false" aria-controls="designMenu">' +
      '<span class="sw" aria-hidden="true"></span>Design' +
      '<svg class="caret" viewBox="0 0 24 24" aria-hidden="true"><path d="M6 9l6 6 6-6"/></svg></button>' +
      '<div class="design-menu" id="designMenu" hidden><h4>Choose a design for this site</h4>' +
      '<div role="radiogroup" aria-label="Site design">' + opts + "</div>" +
      '<p class="fine" style="margin:8px 8px 4px">Your choice is saved in this browser.</p></div></div>';
  }

  function applyTheme(id, persist) {
    var x = THEMES.filter(function (t) { return t.id === id; })[0] || THEMES[0];
    if (x.id === "t1") document.documentElement.removeAttribute("data-theme");
    else document.documentElement.setAttribute("data-theme", x.id);
    if (FONTS[x.id] && !document.querySelector('link[data-theme-font="' + x.id + '"]') && !(document.getElementById("theme-fonts") && document.getElementById("theme-fonts").href.indexOf(FONTS[x.id]) > -1)) {
      var l = document.createElement("link");
      l.rel = "stylesheet"; l.setAttribute("data-theme-font", x.id);
      l.href = "https://fonts.googleapis.com/css2?" + FONTS[x.id] + "&display=swap";
      document.head.appendChild(l);
    }
    var m = document.querySelector('meta[name="theme-color"]');
    if (m) m.setAttribute("content", x.meta);
    document.querySelectorAll(".design-opt").forEach(function (b) {
      b.setAttribute("aria-checked", String(b.getAttribute("data-theme-id") === x.id));
    });
    if (persist) { try { localStorage.setItem(STORE, x.id); } catch (e) {} }
  }

  function wireDesignMenu() {
    var btn = document.getElementById("designBtn");
    var menu = document.getElementById("designMenu");
    if (!btn || !menu) return;
    function open(v) {
      menu.hidden = !v;
      btn.setAttribute("aria-expanded", String(v));
      if (v) {
        var sel = menu.querySelector('[aria-checked="true"]') || menu.querySelector(".design-opt");
        if (sel && window.matchMedia("(min-width: 1041px)").matches) sel.focus();
      }
    }
    btn.addEventListener("click", function () { open(menu.hidden); });
    document.addEventListener("click", function (e) {
      if (!menu.hidden && !menu.contains(e.target) && !btn.contains(e.target)) open(false);
    });
    menu.addEventListener("click", function (e) {
      var b = e.target.closest(".design-opt");
      if (!b) return;
      applyTheme(b.getAttribute("data-theme-id"), true);
      if (window.matchMedia("(max-width: 1040px)").matches) open(false);
    });
    document.addEventListener("keydown", function (e) {
      if (menu.hidden) return;
      if (e.key === "Escape") { open(false); btn.focus(); return; }
      if (e.key === "ArrowDown" || e.key === "ArrowUp") {
        var opts = Array.prototype.slice.call(menu.querySelectorAll(".design-opt"));
        var i = opts.indexOf(document.activeElement);
        var n = e.key === "ArrowDown" ? (i + 1) % opts.length : (i - 1 + opts.length) % opts.length;
        opts[n].focus(); e.preventDefault();
      }
    });
  }

  function util() {
    return '<div class="util"><div class="wrap"><span>Free to use with your own Google Gemini key</span>' +
      '<span class="util-links"><a href="/security">Security</a><a href="/contact">Contact</a></span></div></div>';
  }

  function nav() {
    var items = links.map(function (l) {
      var cur = path === l[0] ? ' aria-current="page"' : "";
      return '<a href="' + l[0] + '"' + cur + ">" + l[1] + "</a>";
    }).join("");
    var cta = (path === "/app" || path === "/register") ? "" : '<a class="btn primary nav-cta" href="/app">Open the tool</a>';
    items += designMenu();
    items += '<div class="nav-item" id="authSlot"></div>';
    return '<div class="site-header" id="siteHeaderBar"><div class="wrap nav">' +
      '<a class="logo" href="/" aria-label="' + SITE.name + ' home">' + logo + "<span>" + SITE.name + "</span></a>" +
      '<button class="nav-toggle" id="navToggle" aria-expanded="false" aria-controls="navLinks">Menu</button>' +
      '<nav class="nav-links" id="navLinks" aria-label="Main">' + items + cta + "</nav></div></div>";
  }

  function footer() {
    return '<footer class="site-footer"><div class="wrap"><div class="foot-grid">' +
      '<div><a class="logo" href="/">' + logo + "<span>" + SITE.name + "</span></a>" +
      '<p class="about-blurb">Turn YouTube lecture videos into formatted, word-for-word Roman Urdu study notes.</p></div>' +
      '<div><h4>Product</h4><ul><li><a href="/app">Notes tool</a></li><li><a href="/account">My account</a></li><li><a href="/features">Features</a></li><li><a href="/how-it-works">How it works</a></li><li><a href="/faq">FAQ</a></li></ul></div>' +
      '<div><h4>Solutions</h4><ul><li><a href="/solutions#students">Students</a></li><li><a href="/solutions#educators">Educators</a></li><li><a href="/solutions#self-learners">Self-learners</a></li></ul></div>' +
      '<div><h4>Company</h4><ul><li><a href="/about">About</a></li><li><a href="/security">Security</a></li><li><a href="/contact">Contact</a></li></ul></div>' +
      '<div><h4>Legal</h4><ul><li><a href="/privacy">Privacy policy</a></li><li><a href="/terms">Terms of use</a></li></ul></div>' +
      '</div><div class="foot-bottom"><span>&copy; ' + new Date().getFullYear() + " " + SITE.name + ". All rights reserved.</span>" +
      "<span>" + SITE.domain + " &middot; Not affiliated with YouTube or Google.</span></div></div></footer>";
  }

  var u = document.getElementById("site-util");
  if (u) u.innerHTML = util();
  var h = document.getElementById("site-header");
  if (h) h.innerHTML = nav();
  var f = document.getElementById("site-footer");
  if (f) f.innerHTML = footer();

  wireDesignMenu();
  applyTheme(currentTheme(), false);

  var t = document.getElementById("navToggle");
  if (t) t.addEventListener("click", function () {
    var bar = document.getElementById("siteHeaderBar");
    var open = bar.classList.toggle("open");
    t.setAttribute("aria-expanded", String(open));
  });


  /* ---------- account area of the header ---------- */
  function esc(s) { var d = document.createElement("div"); d.textContent = s == null ? "" : String(s); return d.innerHTML; }
  var CARET = '<svg class="caret" viewBox="0 0 24 24" aria-hidden="true"><path d="M6 9l6 6 6-6"/></svg>';

  window.SITE_SIGN_OUT = function () {
    var done = function () {
      try { localStorage.removeItem("ru_job_id"); localStorage.removeItem("ru_gemini_key"); } catch (e) {}
      location.href = "/";
    };
    fetch("/api/auth/logout", { method: "POST", credentials: "same-origin" }).then(done, done);
  };

  function renderAuth(me) {
    var slot = document.getElementById("authSlot");
    if (!slot) return;
    if (!me) {
      var next = (path === "/" || path === "/login") ? "" : "?next=" + encodeURIComponent(path);
      slot.innerHTML = '<a class="nav-signin" href="/login' + next + '">Sign in</a>';
      var c = document.querySelector(".nav-cta");  // signed-out visitors are invited to create an account
      if (c) { c.textContent = "Get started"; c.setAttribute("href", "/register"); }
      return;
    }
    var name = me.display_name || me.email.split("@")[0];
    slot.innerHTML = '<button type="button" class="design-btn user-btn" id="userBtn" aria-haspopup="true" aria-expanded="false" aria-controls="userMenu">' +
      (me.avatar_url ? '<img class="avatar" src="' + esc(me.avatar_url) + '" alt="" width="28" height="28" referrerpolicy="no-referrer">'
                     : '<span class="avatar" aria-hidden="true">' + esc(name.charAt(0).toUpperCase()) + "</span>") +
      '<span class="uname">' + esc(name) + "</span>" + CARET + "</button>" +
      '<div class="design-menu user-menu" id="userMenu" hidden><div class="um-head"><b>' + esc(name) + "</b><small>" + esc(me.email) + "</small></div>" +
      '<a class="um-link" href="/app">Notes tool</a><a class="um-link" href="/account">My account</a>' +
      '<button type="button" class="um-link" id="signOutBtn">Sign out</button></div>';
    var btn = document.getElementById("userBtn"), menu = document.getElementById("userMenu");
    btn.addEventListener("click", function () {
      menu.hidden = !menu.hidden;
      btn.setAttribute("aria-expanded", String(!menu.hidden));
    });
    document.addEventListener("click", function (e) {
      if (!menu.hidden && !menu.contains(e.target) && !btn.contains(e.target)) { menu.hidden = true; btn.setAttribute("aria-expanded", "false"); }
    });
    document.addEventListener("keydown", function (e) {
      if (e.key === "Escape" && !menu.hidden) { menu.hidden = true; btn.setAttribute("aria-expanded", "false"); btn.focus(); }
    });
    document.getElementById("signOutBtn").addEventListener("click", window.SITE_SIGN_OUT);
  }
  window.SITE_REFRESH_USER = renderAuth;

  window.SITE_ME.then(function (me) {
    renderAuth(me);
    var need = document.body.getAttribute("data-auth") === "required";
    if (need && !me) { location.replace("/login?next=" + encodeURIComponent(path + location.search)); return; }
    document.body.classList.add("auth-ready");
    if (me && (path === "/login" || path === "/register")) {
      var n = new URLSearchParams(location.search).get("next") || "/app";
      location.replace(/^\/(?!\/)[^\\\s]*$/.test(n) ? n : "/app");
    }
  });

  // breadcrumb inside the page banner of inner pages
  var banner = document.querySelector(".page-head .wrap");
  if (banner && path !== "/") {
    var h1 = banner.querySelector("h1");
    var crumb = document.createElement("nav");
    crumb.className = "crumbs";
    crumb.setAttribute("aria-label", "Breadcrumb");
    crumb.innerHTML = '<a href="/">Home</a><span aria-hidden="true">/</span>' + (h1 ? h1.textContent : "");
    banner.insertBefore(crumb, banner.firstChild);
  }

  document.querySelectorAll("[data-site-email]").forEach(function (el) {
    el.textContent = SITE.email;
    if (el.tagName === "A") el.href = "mailto:" + SITE.email;
  });
  document.querySelectorAll("[data-site-name]").forEach(function (el) { el.textContent = SITE.name; });

  // scroll reveal
  var items = document.querySelectorAll(".reveal");
  if ("IntersectionObserver" in window) {
    var io = new IntersectionObserver(function (entries) {
      entries.forEach(function (e) { if (e.isIntersecting) { e.target.classList.add("in"); io.unobserve(e.target); } });
    }, { rootMargin: "0px 0px -8% 0px", threshold: 0.05 });
    items.forEach(function (el) { io.observe(el); });
  } else {
    items.forEach(function (el) { el.classList.add("in"); });
  }
})();
